public final class DiceUvUnwrapper {
    private static final int TEXTURE_SIZE = 512;
    private static final int FONT_PIXELS_PER_EM = 16;
    private static final int MIN_TEXELS_PER_FONT_PIXEL = 2;
    private static final double GOOD_ENOUGH_USE = 0.9;

    private static final Font NUMBER_FONT = loadFont("/alagard.ttf", 100f);

    private static Font loadFont(String resource, float size) {
        try (InputStream in = DiceUvUnwrapper.class.getResourceAsStream(resource)) {
            return Font.createFont(Font.TRUETYPE_FONT, in).deriveFont(size);
        } catch (Exception e) {
            throw new IllegalStateException("Could not load the number typeface " + resource, e);
        }
    }

    private static final double EDGE_TOLERANCE = 0.05;

    private static final double CELL_PADDING = 0.14;

    private static final double DECAL_LIFT = 0.004;

    private static final int[] DIE_TYPES = {4, 6, 8, 10, 12, 20};
    private static final String FACE_MATERIAL = "material_2";
    private static final String DECAL_MATERIAL = "material_3";

    private DiceUvUnwrapper() {}

    public static void main(String[] args) throws Exception {
        Path assets = Path.of("src/main/resources/assets/polyhedrals");
        for (int sides : DIE_TYPES) {
            unwrap(assets, sides);
        }
        writeNumberTexture(assets, 100, DiceShapes.forSides(100), faceOutlines(assets, 10));
        System.out.println("Done.");
    }

    private static void unwrap(Path assets, int sides) throws Exception {
        DiceShapes.Shape shape = DiceShapes.forSides(sides);
        Path objPath = assets.resolve("models/item/d" + sides + ".obj");
        List<String> solid = readSolid(objPath);
        Layout layout = layout(shape, solid);

        List<String> out = new ArrayList<>(solid);
        out.add(DiceShapes.DECAL_MARKER + ": regenerated by ./gradlew generateDiceUvs ---");
        out.addAll(layout.decalLines());
        Files.write(objPath, out, StandardCharsets.UTF_8);

        writeNumberTexture(assets, sides, shape, layout.outlines());
        System.out.printf(Locale.ROOT, "d%-4d %2d faces -> %dx%d grid%n",
                sides, shape.faceCount(), layout.grid().columns, layout.grid().rows);
    }

    private static List<String> readSolid(Path objPath) throws Exception {
        List<String> lines = Files.readAllLines(objPath, StandardCharsets.UTF_8);
        for (int i = 0; i < lines.size(); i++) {
            if (lines.get(i).startsWith(DiceShapes.DECAL_MARKER)) {
                return new ArrayList<>(lines.subList(0, i));
            }
        }
        return lines;
    }

    private static List<List<double[]>> faceOutlines(Path assets, int sides) throws Exception {
        DiceShapes.Shape shape = DiceShapes.forSides(sides);
        return layout(shape, readSolid(assets.resolve("models/item/d" + sides + ".obj"))).outlines();
    }

    private record Layout(Grid grid, List<String> decalLines, List<List<double[]>> outlines) {}

    private static Layout layout(DiceShapes.Shape shape, List<String> solid) {
        List<double[]> vertices = new ArrayList<>();
        List<String> faceLines = new ArrayList<>();
        String material = null;
        for (String line : solid) {
            if (line.startsWith("v ")) {
                String[] parts = line.trim().split("\\s+");
                vertices.add(new double[] {
                        Double.parseDouble(parts[1]),
                        Double.parseDouble(parts[2]),
                        Double.parseDouble(parts[3])});
            } else if (line.startsWith("usemtl ")) {
                material = line.substring("usemtl ".length()).trim();
            } else if (line.startsWith("f ") && FACE_MATERIAL.equals(material)) {
                faceLines.add(line);
            }
        }
        if (faceLines.isEmpty()) {
            throw new IllegalStateException("no " + FACE_MATERIAL + " faces to unwrap");
        }
        int solidVertices = vertices.size();
        int solidUvs = (int) solid.stream().filter(l -> l.startsWith("vt ")).count();

        Map<Integer, List<String>> byFace = new LinkedHashMap<>();
        for (String face : faceLines) {
            int[] verts = faceVertices(face);
            byFace.computeIfAbsent(nearestFace(shape, triangleNormal(vertices, verts)),
                    unused -> new ArrayList<>()).add(face);
        }
        if (byFace.size() != shape.faceCount()) {
            throw new IllegalStateException("grouped into " + byFace.size()
                    + " number faces but the solid has " + shape.faceCount());
        }

        int[] values = DiceFaceNumbering.valuesFor(shape);
        Grid grid = Grid.forCount(shape.faceCount());
        List<double[]> outVertices = new ArrayList<>();
        List<double[]> outUvs = new ArrayList<>();
        List<String> outFaces = new ArrayList<>();
        List<List<double[]>> outlines = new ArrayList<>();
        for (int i = 0; i < shape.faceCount(); i++) {
            outlines.add(List.of());
        }

        for (Map.Entry<Integer, List<String>> entry : byFace.entrySet()) {
            int face = entry.getKey();
            int cell = cellOf(shape, values[face]);
            double[] normal = normalOf(shape, face);
            double[][] basis = planeBasis(normal);

            Map<Integer, double[]> projected = new LinkedHashMap<>();
            for (String line : entry.getValue()) {
                for (int vertex : faceVertices(line)) {
                    projected.computeIfAbsent(vertex, v -> project(vertices.get(v - 1), basis));
                }
            }

            double turn = uprightAngle(hullOrder(projected.values()), labelFor(shape, values[face]));
            Map<Integer, double[]> turned = new LinkedHashMap<>();
            projected.forEach((vertex, point) -> turned.put(vertex, rotate(point, turn)));

            double[] bounds = bounds(turned.values());
            Map<Integer, Integer> remapped = new LinkedHashMap<>();
            Map<Integer, double[]> unitOf = new LinkedHashMap<>();
            for (Map.Entry<Integer, double[]> point : turned.entrySet()) {
                double[] source = vertices.get(point.getKey() - 1);
                outVertices.add(new double[] {
                        source[0] + normal[0] * DECAL_LIFT,
                        source[1] + normal[1] * DECAL_LIFT,
                        source[2] + normal[2] * DECAL_LIFT});
                double[] unit = normalise(point.getValue(), bounds);
                unitOf.put(point.getKey(), unit);
                outUvs.add(grid.place(cell, unit));
                remapped.put(point.getKey(), outVertices.size());
            }
            outlines.set(cell, hullOrder(unitOf.values()));

            for (String line : entry.getValue()) {
                outFaces.add(rebuild(line, remapped, solidVertices, solidUvs));
            }
        }

        List<String> lines = new ArrayList<>();
        for (double[] v : outVertices) {
            lines.add(String.format(Locale.ROOT, "v %.6f %.6f %.6f", v[0], v[1], v[2]));
        }
        for (double[] uv : outUvs) {
            lines.add(String.format(Locale.ROOT, "vt %.6f %.6f", uv[0], uv[1]));
        }
        lines.add("usemtl " + DECAL_MATERIAL);
        lines.addAll(outFaces);
        return new Layout(grid, lines, outlines);
    }

    private static int cellOf(DiceShapes.Shape shape, int value) {
        return shape.sides() == 100 ? value / 10 : value - 1;
    }

    private static String labelFor(DiceShapes.Shape shape, int value) {
        return shape.sides() == 100
                ? String.format(Locale.ROOT, "%02d", value)
                : Integer.toString(value);
    }

    private static java.awt.Shape glyphFor(String label) {
        return NUMBER_FONT.createGlyphVector(
                new java.awt.font.FontRenderContext(null, true, true), label).getOutline();
    }

    private static double uprightAngle(List<double[]> outline, String label) {
        java.awt.Shape glyph = glyphFor(label);
        List<List<double[]>> contours = flatten(glyph);
        List<double[]> glyphPoints = points(contours);
        double[] glyphCentre = centreOfArea(contours);

        double best = 0;
        double bestFit = -1;
        for (int i = 0; i < outline.size(); i++) {
            double[] a = outline.get(i);
            double[] b = outline.get((i + 1) % outline.size());
            double angle = -Math.atan2(b[1] - a[1], b[0] - a[0]);
            List<double[]> candidate = rotateAll(outline, angle);
            double[] centre = centreOfArea(List.of(candidate));
            if (centre[1] > rotate(a, angle)[1]) {
                angle += Math.PI;
                candidate = rotateAll(outline, angle);
                centre = centreOfArea(List.of(candidate));
            }

            double fit = largestFit(glyphPoints, glyphCentre, candidate, centre,
                    EDGE_TOLERANCE * extent(candidate));
            if (fit > bestFit) {
                bestFit = fit;
                best = angle;
            }
        }
        return best;
    }

    private static double[] rotate(double[] point, double angle) {
        double cos = Math.cos(angle);
        double sin = Math.sin(angle);
        return new double[] {point[0] * cos - point[1] * sin, point[0] * sin + point[1] * cos};
    }

    private static List<double[]> rotateAll(List<double[]> points, double angle) {
        List<double[]> turned = new ArrayList<>(points.size());
        for (double[] p : points) {
            turned.add(rotate(p, angle));
        }
        return turned;
    }

    private static void writeNumberTexture(Path assets, int sides, DiceShapes.Shape shape,
                                      List<List<double[]>> outlines) throws Exception {
        int[] values = DiceFaceNumbering.valuesFor(shape);
        Grid grid = Grid.forCount(shape.faceCount());
        int count = shape.faceCount();

        int[] cellValue = new int[count];
        for (int face = 0; face < count; face++) {
            cellValue[cellOf(shape, values[face])] = values[face];
        }

        java.awt.Shape[] glyphs = new java.awt.Shape[count];
        List<List<double[]>> glyphPoints = new ArrayList<>();
        double[][] glyphCentres = new double[count][];
        for (int cell = 0; cell < count; cell++) {
            glyphs[cell] = glyphFor(labelFor(shape, cellValue[cell]));
            java.awt.geom.Rectangle2D bounds = glyphs[cell].getBounds2D();
            glyphCentres[cell] = new double[] {bounds.getCenterX(), bounds.getCenterY()};
            glyphPoints.add(points(flatten(glyphs[cell])));
        }

        double fontPixel = NUMBER_FONT.getSize2D() / FONT_PIXELS_PER_EM;
        int baseCell = TEXTURE_SIZE / Math.max(grid.columns, grid.rows) / 16 * 16;
        double fitPerCellPixel = largestCommonFit(glyphPoints, glyphCentres, outlines, grid, baseCell) * fontPixel / baseCell;
        int cellPixels = baseCell;
        double bestUse = 0;
        for (int candidate = baseCell; candidate <= baseCell * 2 && candidate * Math.max(grid.columns, grid.rows) <= 1024; candidate += 16) {
            double fit = fitPerCellPixel * candidate;
            double use = fit >= MIN_TEXELS_PER_FONT_PIXEL ? Math.floor(fit) / fit : 0;
            if (use > bestUse) {
                bestUse = use;
                cellPixels = candidate;
            }
            if (use >= GOOD_ENOUGH_USE) break;
        }
        List<List<double[]>> faces = new ArrayList<>();
        for (int cell = 0; cell < count; cell++) {
            faces.add(facePolygon(outlines.get(cell), cell, grid, cellPixels));
        }
        double size = Math.floor(fitPerCellPixel * cellPixels) / fontPixel;

        BufferedImage image = new BufferedImage(
                cellPixels * grid.columns, cellPixels * grid.rows, BufferedImage.TYPE_INT_ARGB);
        Graphics2D g = image.createGraphics();
        g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_OFF);
        g.setColor(Color.WHITE);
        for (int cell = 0; cell < count; cell++) {
            double[] centre = centreOfArea(List.of(faces.get(cell)));
            AffineTransform place = AffineTransform.getTranslateInstance(
                    Math.round(centre[0] - size * glyphCentres[cell][0]),
                    Math.round(centre[1] - size * glyphCentres[cell][1]));
            place.scale(size, size);
            g.fill(place.createTransformedShape(glyphs[cell]));
        }
        g.dispose();

        System.out.println("d" + sides + ": " + Math.round(size * fontPixel) + " texels per font pixel ("
                + Math.round(bestUse * 100) + "% of the room), " + image.getWidth() + "x" + image.getHeight());
        ImageIO.write(image, "PNG", assets.resolve("textures/item/d" + sides + "_numbers.png").toFile());
    }

    private static double largestCommonFit(List<List<double[]>> glyphPoints, double[][] glyphCentres,
                                           List<List<double[]>> outlines, Grid grid, int cellPixels) {
        double size = Double.MAX_VALUE;
        for (int cell = 0; cell < glyphPoints.size(); cell++) {
            List<double[]> face = facePolygon(outlines.get(cell), cell, grid, cellPixels);
            size = Math.min(size, largestFit(glyphPoints.get(cell), glyphCentres[cell], face,
                    centreOfArea(List.of(face)), EDGE_TOLERANCE * extent(face)));
        }
        return size;
    }

    private static List<double[]> facePolygon(List<double[]> outline, int cell, Grid grid, int cellPixels) {
        double x = (cell % grid.columns) * cellPixels;
        double y = (cell / grid.columns) * cellPixels;
        List<double[]> polygon = new ArrayList<>(outline.size());
        for (double[] corner : outline) {
            polygon.add(new double[] {
                    x + (CELL_PADDING + corner[0] * (1 - 2 * CELL_PADDING)) * cellPixels,
                    y + (CELL_PADDING + corner[1] * (1 - 2 * CELL_PADDING)) * cellPixels});
        }
        return polygon;
    }

    private static double largestFit(List<double[]> glyph, double[] glyphCentre,
                                     List<double[]> face, double[] faceCentre, double tolerance) {
        double limit = Double.MAX_VALUE;
        for (int i = 0; i < face.size(); i++) {
            double[] a = face.get(i);
            double[] b = face.get((i + 1) % face.size());
            double nx = -(b[1] - a[1]);
            double ny = b[0] - a[0];
            double length = Math.hypot(nx, ny);
            if (length == 0) continue;
            nx /= length;
            ny /= length;
            double room = nx * (faceCentre[0] - a[0]) + ny * (faceCentre[1] - a[1]);
            if (room < 0) {
                nx = -nx;
                ny = -ny;
                room = -room;
            }
            double usable = room - tolerance;
            for (double[] p : glyph) {
                double reach = nx * (p[0] - glyphCentre[0]) + ny * (p[1] - glyphCentre[1]);
                if (reach > 0) {
                    limit = Math.min(limit, usable / reach);
                }
            }
        }
        return Math.max(0, limit);
    }

    private static double extent(List<double[]> polygon) {
        double[] box = bounds(polygon);
        return Math.max(box[2] - box[0], box[3] - box[1]);
    }

    private static double[] centreOfArea(List<List<double[]>> contours) {
        double area = 0, cx = 0, cy = 0;
        for (List<double[]> contour : contours) {
            for (int i = 0; i < contour.size(); i++) {
                double[] a = contour.get(i);
                double[] b = contour.get((i + 1) % contour.size());
                double cross = a[0] * b[1] - b[0] * a[1];
                area += cross;
                cx += (a[0] + b[0]) * cross;
                cy += (a[1] + b[1]) * cross;
            }
        }
        if (Math.abs(area) < 1e-9) {
            double[] box = bounds(points(contours));
            return new double[] {(box[0] + box[2]) / 2, (box[1] + box[3]) / 2};
        }
        return new double[] {cx / (3 * area), cy / (3 * area)};
    }

    private static List<List<double[]>> flatten(java.awt.Shape shape) {
        List<List<double[]>> contours = new ArrayList<>();
        List<double[]> current = null;
        double[] segment = new double[6];
        for (var it = shape.getPathIterator(null, 0.2); !it.isDone(); it.next()) {
            switch (it.currentSegment(segment)) {
                case PathIterator.SEG_MOVETO -> {
                    current = new ArrayList<>();
                    contours.add(current);
                    current.add(new double[] {segment[0], segment[1]});
                }
                case PathIterator.SEG_LINETO -> {
                    if (current != null) current.add(new double[] {segment[0], segment[1]});
                }
                default -> { }
            }
        }
        return contours;
    }

    private static List<double[]> points(List<List<double[]>> contours) {
        List<double[]> all = new ArrayList<>();
        contours.forEach(all::addAll);
        return all;
    }

    private record Grid(int columns, int rows) {
        static Grid forCount(int count) {
            int columns = (int) Math.ceil(Math.sqrt(count));
            return new Grid(columns, (int) Math.ceil(count / (double) columns));
        }

        double[] place(int cell, double[] unit) {
            double u = (cell % columns + CELL_PADDING + unit[0] * (1 - 2 * CELL_PADDING)) / columns;
            double v = (cell / columns + CELL_PADDING + unit[1] * (1 - 2 * CELL_PADDING)) / rows;
            return new double[] {u, v};
        }
    }

    private static int[] faceVertices(String line) {
        String[] parts = line.trim().split("\\s+");
        int[] verts = new int[parts.length - 1];
        for (int i = 1; i < parts.length; i++) {
            verts[i - 1] = Integer.parseInt(parts[i].split("/")[0]);
        }
        return verts;
    }

    private static String rebuild(String line, Map<Integer, Integer> remapped,
                                  int solidVertices, int solidUvs) {
        String[] parts = line.trim().split("\\s+");
        StringBuilder out = new StringBuilder("f");
        for (int i = 1; i < parts.length; i++) {
            String[] refs = parts[i].split("/", -1);
            int index = remapped.get(Integer.parseInt(refs[0]));
            out.append(' ').append(solidVertices + index).append('/').append(solidUvs + index);
            if (refs.length > 2 && !refs[2].isEmpty()) out.append('/').append(refs[2]);
        }
        return out.toString();
    }

    private static double[] triangleNormal(List<double[]> vertices, int[] verts) {
        double[] a = vertices.get(verts[0] - 1);
        double[] b = vertices.get(verts[1] - 1);
        double[] c = vertices.get(verts[2] - 1);
        double[] u = {b[0] - a[0], b[1] - a[1], b[2] - a[2]};
        double[] v = {c[0] - a[0], c[1] - a[1], c[2] - a[2]};
        double[] n = {u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]};
        double length = Math.sqrt(n[0] * n[0] + n[1] * n[1] + n[2] * n[2]);
        return new double[] {n[0] / length, n[1] / length, n[2] / length};
    }

    private static int nearestFace(DiceShapes.Shape shape, double[] normal) {
        int best = -1;
        double bestDot = -Double.MAX_VALUE;
        for (int face = 0; face < shape.faceCount(); face++) {
            double[] candidate = normalOf(shape, face);
            double dot = normal[0] * candidate[0] + normal[1] * candidate[1] + normal[2] * candidate[2];
            if (dot > bestDot) {
                bestDot = dot;
                best = face;
            }
        }
        return best;
    }

    private static double[] normalOf(DiceShapes.Shape shape, int face) {
        Vector3d normal = shape.faceNormal(face);
        return new double[] {normal.x, normal.y, normal.z};
    }

    private static double[][] planeBasis(double[] normal) {
        double[] reference = Math.abs(normal[1]) > 0.95 ? new double[] {0, 0, 1} : new double[] {0, 1, 0};
        double dot = reference[0] * normal[0] + reference[1] * normal[1] + reference[2] * normal[2];
        double[] up = {
                reference[0] - dot * normal[0],
                reference[1] - dot * normal[1],
                reference[2] - dot * normal[2]};
        double length = Math.sqrt(up[0] * up[0] + up[1] * up[1] + up[2] * up[2]);
        up = new double[] {up[0] / length, up[1] / length, up[2] / length};
        double[] right = {
                up[1] * normal[2] - up[2] * normal[1],
                up[2] * normal[0] - up[0] * normal[2],
                up[0] * normal[1] - up[1] * normal[0]};
        return new double[][] {right, up};
    }

    private static double[] project(double[] point, double[][] basis) {
        return new double[] {
                point[0] * basis[0][0] + point[1] * basis[0][1] + point[2] * basis[0][2],
                -(point[0] * basis[1][0] + point[1] * basis[1][1] + point[2] * basis[1][2])};
    }

    private static double[] bounds(Iterable<double[]> points) {
        double minX = Double.MAX_VALUE, minY = Double.MAX_VALUE;
        double maxX = -Double.MAX_VALUE, maxY = -Double.MAX_VALUE;
        for (double[] p : points) {
            minX = Math.min(minX, p[0]);
            maxX = Math.max(maxX, p[0]);
            minY = Math.min(minY, p[1]);
            maxY = Math.max(maxY, p[1]);
        }
        return new double[] {minX, minY, maxX, maxY};
    }

    private static double[] normalise(double[] point, double[] bounds) {
        double width = bounds[2] - bounds[0];
        double height = bounds[3] - bounds[1];
        double extent = Math.max(width, height);
        return new double[] {
                (point[0] - bounds[0] + (extent - width) / 2) / extent,
                (point[1] - bounds[1] + (extent - height) / 2) / extent};
    }

    private static List<double[]> hullOrder(Iterable<double[]> points) {
        List<double[]> corners = new ArrayList<>();
        points.forEach(corners::add);
        double cx = 0, cy = 0;
        for (double[] p : corners) {
            cx += p[0];
            cy += p[1];
        }
        double centreX = cx / corners.size();
        double centreY = cy / corners.size();
        corners.sort((a, b) -> Double.compare(
                Math.atan2(a[1] - centreY, a[0] - centreX),
                Math.atan2(b[1] - centreY, b[0] - centreX)));
        return corners;
    }
}
